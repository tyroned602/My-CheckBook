const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync('transfers.js','utf8').split('const parseOriginalEntry')[0],ctx);
const ledger={accounts:[{id:'paypal',name:'PayPal Business',balance:73.37},{id:'cash',name:'Cash',balance:70}],transactions:[]};
const original=JSON.stringify(ledger);
assert.equal(ctx.parseMoneyCents('$1,200.50'),120050);
assert.equal(ctx.parseMoneyCents('0.01'),1);
for(const invalid of ['1,20','1.005','-20','0','Infinity','abc'])assert.throws(()=>ctx.parseMoneyCents(invalid));
const items=ctx.makeTransfer(ledger,'paypal','cash','20.01','2026-10-28T12:00:00','t1');
assert.equal(items.reduce((sum,t)=>sum+Math.round(t.amount*100),0),0);
const next=ctx.applyTransfer(ledger,items);
assert.equal(next.accounts[0].balance,53.36);assert.equal(next.accounts[1].balance,90.01);
assert.equal(next.transactions.length,2);assert.equal(next.transactions[0].transferId,next.transactions[1].transferId);
assert.equal(JSON.stringify(ledger),original);
assert.throws(()=>ctx.makeTransfer(ledger,'cash','cash','20','2026-10-28','t2'));
assert.throws(()=>ctx.makeTransfer(ledger,'missing','cash','20','2026-10-28','t2'));
const failedLedger=JSON.parse(original);failedLedger.accounts.pop();
assert.throws(()=>ctx.applyTransfer(failedLedger,items));assert.equal(failedLedger.accounts[0].balance,73.37);
console.log('Passed: comma amounts, invalid input, paired balances, conserved total, and no partial update on missing account.');
